"""NLE & Compositor interchange export (Foundry Nuke .nk and Apple/Resolve FCPXML 1.10)."""

from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET
from fractions import Fraction
from pathlib import Path
from typing import Optional

from backend.natural_sort import natsorted


def _detect_sequence_pattern(directory: str) -> tuple[str, int, int] | None:
    """Return (printf_pattern_path, first_frame, last_frame) for frames in `directory`."""
    if not directory or not os.path.isdir(directory):
        return None
    exts = {".png", ".jpg", ".jpeg", ".exr", ".tif", ".tiff"}
    files = natsorted(
        f for f in os.listdir(directory)
        if os.path.splitext(f)[1].lower() in exts
    )
    if not files:
        return None
    first = files[0]
    m = re.match(r"^(.*?)(\d+)(\.\w+)$", first)
    if not m:
        full = os.path.join(directory, first).replace("\\", "/")
        return full, 1, 1
    prefix, digits, suffix = m.group(1), m.group(2), m.group(3)
    pat = f"{prefix}%0{len(digits)}d{suffix}"
    first_num = int(digits)
    last_num = first_num + len(files) - 1
    m_last = re.match(r"^(.*?)(\d+)(\.\w+)$", files[-1])
    if m_last:
        last_num = int(m_last.group(2))
    full = os.path.join(directory, pat).replace("\\", "/")
    return full, first_num, max(first_num, last_num)


def _find_clip_source_video(clip) -> str | None:
    src_dir = os.path.join(clip.root_path, "Source")
    if os.path.isdir(src_dir):
        for fn in sorted(os.listdir(src_dir)):
            if os.path.splitext(fn)[1].lower() in (".mp4", ".mov", ".mxf", ".mkv", ".avi"):
                return os.path.join(src_dir, fn).replace("\\", "/")
    if getattr(clip, "input_asset", None) is not None and clip.input_asset.asset_type == "video":
        return str(clip.input_asset.path).replace("\\", "/")
    return None


def _fps_fraction(fps: float) -> tuple[int, int]:
    """Return rational frame duration (num, den) for FCPXML time math."""
    f = float(fps) if fps > 0 else 24.0
    if abs(f - 23.976) < 0.02:
        return 1001, 24000
    if abs(f - 29.97) < 0.02:
        return 1001, 30000
    if abs(f - 59.94) < 0.02:
        return 1001, 60000
    frac = Fraction(1.0 / f).limit_denominator(10000)
    return frac.numerator, frac.denominator


def export_nuke_script(
    clip,
    out_path: str,
    *,
    fps: float = 24.0,
    timecode: str = "01:00:00:00",
) -> str:
    """Write a Foundry Nuke `.nk` compositing script wired with Source, FG, and Matte Read nodes."""
    clip_name = getattr(clip, "name", "clip")
    root_path = getattr(clip, "root_path", "")
    out_dir = getattr(clip, "output_dir", root_path)

    src_seq = _detect_sequence_pattern(os.path.join(root_path, "Frames"))
    if src_seq is None and getattr(clip, "input_asset", None) is not None and clip.input_asset.asset_type == "sequence":
        src_seq = _detect_sequence_pattern(clip.input_asset.path)
    src_vid = _find_clip_source_video(clip)

    fg_seq = _detect_sequence_pattern(os.path.join(out_dir, "FG"))
    matte_seq = _detect_sequence_pattern(os.path.join(out_dir, "Matte"))
    comp_seq = _detect_sequence_pattern(os.path.join(out_dir, "Comp"))

    w = getattr(getattr(clip, "input_asset", None), "width", 1920) or 1920
    h = getattr(getattr(clip, "input_asset", None), "height", 1080) or 1080
    fc = getattr(getattr(clip, "input_asset", None), "frame_count", 100) or 100

    ref_seq = fg_seq or comp_seq or src_seq
    first_f = ref_seq[1] if ref_seq else 0
    last_f = ref_seq[2] if ref_seq else max(0, fc - 1)

    lines: list[str] = [
        "# Generated by CorridorKey 2.0",
        "Root {",
        " inputs 0",
        f" frame {first_f}",
        f" first_frame {first_f}",
        f" last_frame {last_f}",
        " lock_range true",
        f" fps {fps:.3f}",
        f' format "{w} {h} 0 0 {w} {h} 1 CorridorKey"',
        "}",
    ]

    # Node 1: Source BG/Plate
    src_file = src_seq[0] if src_seq else (src_vid or f"{root_path}/Frames/frame_%06d.png".replace("\\", "/"))
    src_first, src_last = (src_seq[1], src_seq[2]) if src_seq else (first_f, last_f)
    lines.extend([
        "Read {",
        " inputs 0",
        f" file_type {os.path.splitext(src_file)[1].lstrip('.').lower() or 'png'}",
        f" file {{{src_file}}}",
        f" first {src_first}",
        f" last {src_last}",
        " name Read_Source",
        " xpos -220",
        " ypos -200",
        "}",
    ])

    # Node 2: Matte Read (alpha source)
    matte_file = matte_seq[0] if matte_seq else f"{out_dir}/Matte/frame_%06d.png".replace("\\", "/")
    m_first, m_last = (matte_seq[1], matte_seq[2]) if matte_seq else (first_f, last_f)
    lines.extend([
        "Read {",
        " inputs 0",
        f" file {{{matte_file}}}",
        f" first {m_first}",
        f" last {m_last}",
        " name Read_Matte",
        " xpos 180",
        " ypos -200",
        "}",
    ])

    # Node 3: FG Read (despilled foreground)
    fg_file = fg_seq[0] if fg_seq else (comp_seq[0] if comp_seq else f"{out_dir}/FG/frame_%06d.png".replace("\\", "/"))
    f_first, f_last = (fg_seq[1], fg_seq[2]) if fg_seq else (first_f, last_f)
    lines.extend([
        "Read {",
        " inputs 0",
        f" file {{{fg_file}}}",
        f" first {f_first}",
        f" last {f_last}",
        " name Read_FG",
        " xpos 0",
        " ypos -200",
        "}",
    ])

    # Wire Read_Matte -> Read_FG -> Copy -> Premult -> Merge2 -> Write
    # In Nuke .nk stack semantics, nodes consume previous stack nodes via `inputs`.
    lines.extend([
        "Copy {",
        " inputs 2",
        " from0 rgba.red",
        " to0 rgba.alpha",
        " name Copy_Alpha",
        " xpos 60",
        " ypos -80",
        "}",
        "Premult {",
        " name Premult_FG",
        " xpos 60",
        " ypos -10",
        "}",
        "Merge2 {",
        " inputs 2",
        " operation over",
        " name Comp_Over_Source",
        " xpos -60",
        " ypos 80",
        "}",
        "Write {",
        f' file "{{{os.path.join(out_dir, f"{clip_name}_nuke_comp_%06d.exr").replace(os.sep, "/")}}}"',
        " file_type exr",
        f" first {first_f}",
        f" last {last_f}",
        " name Write_Comp",
        " xpos -60",
        " ypos 160",
        "}",
    ])

    parent = os.path.dirname(out_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return out_path


def export_fcpxml(
    clip,
    out_path: str,
    *,
    fps: float = 24.0,
    timecode: str = "01:00:00:00",
) -> str:
    """Write an Apple Final Cut Pro / DaVinci Resolve compatible FCPXML v1.10 project file."""
    clip_name = getattr(clip, "name", "clip")
    root_path = getattr(clip, "root_path", "")
    out_dir = getattr(clip, "output_dir", root_path)

    w = getattr(getattr(clip, "input_asset", None), "width", 1920) or 1920
    h = getattr(getattr(clip, "input_asset", None), "height", 1080) or 1080
    fc = getattr(getattr(clip, "input_asset", None), "frame_count", 100) or 100

    fd_num, fd_den = _fps_fraction(fps)
    dur_str = f"{fd_num * max(1, int(fc))}/{fd_den}s"
    fd_str = f"{fd_num}/{fd_den}s"

    # Prefer rendered cutout .mov or comp .mp4 or sequence first frame
    asset_path = None
    exports_dir = os.path.join(root_path, "_EXPORTS")
    for cand_dir in (exports_dir, out_dir, root_path):
        if os.path.isdir(cand_dir):
            vids = sorted(
                fn for fn in os.listdir(cand_dir)
                if fn.lower().endswith((".mov", ".mp4"))
            )
            if vids:
                asset_path = os.path.join(cand_dir, vids[0])
                break
    if asset_path is None:
        comp_seq = _detect_sequence_pattern(os.path.join(out_dir, "Comp"))
        fg_seq = _detect_sequence_pattern(os.path.join(out_dir, "FG"))
        seq = comp_seq or fg_seq
        if seq is not None:
            asset_path = seq[0]
        else:
            asset_path = _find_clip_source_video(clip) or os.path.join(out_dir, "Comp", "frame_%06d.png")

    asset_uri = Path(os.path.abspath(asset_path)).as_uri() if os.path.exists(asset_path) else ("file:///" + asset_path.replace("\\", "/").lstrip("/"))

    root = ET.Element("fcpxml", version="1.10")
    resources = ET.SubElement(root, "resources")
    ET.SubElement(
        resources,
        "format",
        id="r1",
        name=f"FFVideoFormat{h}p{int(round(fps))}",
        frameDuration=fd_str,
        width=str(w),
        height=str(h),
    )
    asset_el = ET.SubElement(
        resources,
        "asset",
        id="r2",
        name=clip_name,
        start="0s",
        duration=dur_str,
        hasVideo="1",
        format="r1",
    )
    ET.SubElement(asset_el, "media-rep", kind="original-media", src=asset_uri)

    library = ET.SubElement(root, "library")
    event = ET.SubElement(library, "event", name="CorridorKey 2.0")
    project = ET.SubElement(event, "project", name=clip_name)
    sequence = ET.SubElement(
        project,
        "sequence",
        format="r1",
        duration=dur_str,
        tcStart="0s",
        tcFormat="NDF",
    )
    spine = ET.SubElement(sequence, "spine")
    ET.SubElement(
        spine,
        "asset-clip",
        ref="r2",
        offset="0s",
        name=clip_name,
        start="0s",
        duration=dur_str,
        tcFormat="NDF",
    )

    tree = ET.ElementTree(root)
    if hasattr(ET, "indent"):
        ET.indent(tree, space="  ")
    parent = os.path.dirname(out_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    tree.write(out_path, encoding="utf-8", xml_declaration=True)
    return out_path


def export_ae_jsx(
    clip,
    out_path: str,
    *,
    fps: float = 24.0,
) -> str:
    """Write an Adobe After Effects ExtendScript (`.jsx`) builder importing Source, FG, and Matte."""
    clip_name = getattr(clip, "name", "clip")
    root_path = getattr(clip, "root_path", "")
    out_dir = getattr(clip, "output_dir", root_path)

    fg_seq = _detect_sequence_pattern(os.path.join(out_dir, "FG"))
    matte_seq = _detect_sequence_pattern(os.path.join(out_dir, "Matte"))
    comp_seq = _detect_sequence_pattern(os.path.join(out_dir, "Comp"))
    src_vid = _find_clip_source_video(clip)

    def _first_file_of(seq_info) -> str:
        if seq_info is None:
            return ""
        d = os.path.dirname(seq_info[0])
        if os.path.isdir(d):
            fs = natsorted(f for f in os.listdir(d) if os.path.splitext(f)[1].lower() in (".png", ".exr", ".jpg", ".tif"))
            if fs:
                return os.path.join(d, fs[0]).replace("\\", "/")
        return seq_info[0]

    fg_first = _first_file_of(fg_seq or comp_seq)
    matte_first = _first_file_of(matte_seq)
    safe_name = clip_name.replace('"', '\\"')
    src_js = (src_vid or "").replace("\\", "/")

    script = f"""// Generated by CorridorKey 2.0 — Run via File > Scripts > Run Script File...
app.beginUndoGroup("CorridorKey Import - {safe_name}");
(function() {{
    var proj = app.project || app.newProject();
    var compName = "CK2_{safe_name}";
    function importSeq(pathStr, asSeq) {{
        if (!pathStr) return null;
        var f = new File(pathStr);
        if (!f.exists) return null;
        var io = new ImportOptions(f);
        io.sequence = Boolean(asSeq);
        try {{ return proj.importFile(io); }} catch (e) {{ return null; }}
    }}
    var fgItem = importSeq("{fg_first}", true);
    var matteItem = importSeq("{matte_first}", true);
    var srcItem = importSeq("{src_js}", false);
    var refItem = fgItem || srcItem || matteItem;
    if (!refItem) {{ alert("No CorridorKey media found for {safe_name}"); return; }}
    var comp = proj.items.addComp(compName, refItem.width, refItem.height, 1.0, refItem.duration || 5.0, {fps:.3f});
    if (srcItem) comp.layers.add(srcItem);
    if (fgItem) {{
        var fgLayer = comp.layers.add(fgItem);
        if (matteItem) {{
            var matteLayer = comp.layers.add(matteItem);
            matteLayer.enabled = false;
            fgLayer.setTrackMatte(matteLayer, TrackMatteType.LUMA);
        }}
    }}
    comp.openInViewer();
}})();
app.endUndoGroup();
"""
    parent = os.path.dirname(out_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(script)
    return out_path


def export_fusion_comp(
    clip,
    out_path: str,
    *,
    fps: float = 24.0,
) -> str:
    """Write a Blackmagic DaVinci Resolve / Fusion `.comp` node graph Lua table."""
    clip_name = getattr(clip, "name", "clip")
    root_path = getattr(clip, "root_path", "")
    out_dir = getattr(clip, "output_dir", root_path)

    fg_seq = _detect_sequence_pattern(os.path.join(out_dir, "FG"))
    matte_seq = _detect_sequence_pattern(os.path.join(out_dir, "Matte"))
    comp_seq = _detect_sequence_pattern(os.path.join(out_dir, "Comp"))

    def _first_file(seq_info, fallback: str) -> str:
        if seq_info is not None:
            d = os.path.dirname(seq_info[0])
            if os.path.isdir(d):
                fs = natsorted(f for f in os.listdir(d) if os.path.splitext(f)[1].lower() in (".png", ".exr", ".jpg", ".tif"))
                if fs:
                    return os.path.join(d, fs[0]).replace("\\", "/")
        return fallback.replace("\\", "/")

    fg_path = _first_file(fg_seq or comp_seq, os.path.join(out_dir, "FG", "frame_000000.png"))
    matte_path = _first_file(matte_seq, os.path.join(out_dir, "Matte", "frame_000000.png"))
    fc = getattr(getattr(clip, "input_asset", None), "frame_count", 100) or 100
    last_f = max(0, int(fc) - 1)

    content = f"""Composition {{
\tCurrentTime = 0,
\tRenderRange = {{ 0, {last_f} }},
\tGlobalRange = {{ 0, {last_f} }},
\tTools = {{
\t\tLoaderFG = Loader {{
\t\t\tClips = {{ Clip {{ ID = "Clip1", Filename = "{fg_path}", Length = {fc} }} }},
\t\t\tViewInfo = OperatorInfo {{ Pos = {{ 220, 80 }} }},
\t\t}},
\t\tLoaderMatte = Loader {{
\t\t\tClips = {{ Clip {{ ID = "Clip1", Filename = "{matte_path}", Length = {fc} }} }},
\t\t\tViewInfo = OperatorInfo {{ Pos = {{ 220, 160 }} }},
\t\t}},
\t\tMatteControl1 = MatteControl {{
\t\t\tInputs = {{
\t\t\t\tBackground = Input {{ SourceOp = "LoaderFG", Source = "Output" }},
\t\t\t\tGarbage.Matte = Input {{ SourceOp = "LoaderMatte", Source = "Output" }},
\t\t\t}},
\t\t\tViewInfo = OperatorInfo {{ Pos = {{ 420, 120 }} }},
\t\t}},
\t\tSaver1 = Saver {{
\t\t\tInputs = {{
\t\t\t\tClip = Input {{ Value = Clip {{ Filename = "{out_dir.replace(os.sep, '/')}/{clip_name}_fusion.mov" }} }},
\t\t\t\tInput = Input {{ SourceOp = "MatteControl1", Source = "Output" }},
\t\t\t}},
\t\t\tViewInfo = OperatorInfo {{ Pos = {{ 620, 120 }} }},
\t\t}},
\t}},
\tPrefs = {{ Comp = {{ FrameFormat = {{ Rate = {fps:.3f} }} }} }},
}}
"""
    parent = os.path.dirname(out_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    return out_path
